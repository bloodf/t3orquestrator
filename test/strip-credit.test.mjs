// Tool and model credit is removed from a unit's own commits before they are integrated.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { createGit, defaultExec } from '../lib/git.mjs';
import {
  creditedCommits, moveBranch, stripCredit, stripUnitCredit,
} from '../lib/strip-credit.mjs';

test('stripCredit: drops credit trailers and generated-with lines; keeps people and everything else byte for byte', () => {
  const msg = 'feat: add export\n\nBody line.\n\nCo-Authored-By: Claude Sonnet 5.5 <noreply@anthropic.com>\nCo-authored-by: Ana Lima <ana@example.com>\nCo-authored-by: Cursor <cursoragent@cursor.com>\n';
  assert.equal(stripCredit(msg), 'feat: add export\n\nBody line.\n\nCo-authored-by: Ana Lima <ana@example.com>\n');
  assert.equal(stripCredit('fix: a\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)\n\nCo-Authored-By: Claude <noreply@anthropic.com>\n'), 'fix: a\n');
  for (const line of ['Assisted-by: GPT-5 Codex', 'Generated-by: Gemini (google-labs)', 'co-authored-by: Kimi K2 <bot@moonshot.ai>', 'Co-authored-by: Grok <x@xai.com>',
    'Co-Authored-By: GitHub Copilot <198982749+Copilot@users.noreply.github.com>', 'Co-authored-by: minimax-m2 <m@x.y>', 'Generated by OpenAI tooling',
    'Co-authored-by: renovate[bot] <29139614+renovate[bot]@users.noreply.github.com>', 'Co-authored-by: Someone <noreply@z.ai>', 'Co-authored-by: Devstral 2 <d@x.y>',
    'Co-authored-by: Claude Opus 5.5 <x@y.z>', 'Co-authored-by: claude-fable-5-2', 'Co-authored-by: OpenCode <a@b.c>', 'Co-authored-by: Jane <jane@anthropic.com>']) {
    assert.equal(stripCredit(`docs: x\n\n${line}`), 'docs: x', line);
  }
  const human = 'refactor: tidy\n\nThe generated parser is faster; see the Claude Shannon note.\nReviewed-by: Bob <bob@example.com>\nCo-authored-by: Gemma Ray <gemma@example.com>';
  assert.equal(stripCredit(human), human); // same string: nothing to drop
  // people named like a tool, a vendor's staff, indented examples and prose stay
  for (const line of ['Co-authored-by: Claude Dubois <claude@example.fr>', 'Co-authored-by: Kimi Raikkonen <k@f1.fi>', 'Co-authored-by: Jane Doe <jane@openai.com>',
    'Co-authored-by: Cursor Smith <c@x>', '    Co-authored-by: Claude <noreply@anthropic.com>', 'Generated by cursor movement', 'Co-authored-by: Claudette <c@example.com>']) {
    const msg = `docs: x\n\n${line}`;
    assert.equal(stripCredit(msg), msg, line);
  }
  assert.equal(stripCredit(''), '');
  assert.equal(stripCredit('feat: x\r\n\r\nCo-Authored-By: Claude <noreply@anthropic.com>\r\n'), 'feat: x\r\n');
});

test('creditedCommits: the commits of a `log -z --format=%H%x00%e%x00%B` whose UTF-8 message still credits a tool or model', () => {
  const log = `${'a'.repeat(40)}\0\0feat: a\n\nCo-Authored-By: Claude <noreply@anthropic.com>\n\0\n${'b'.repeat(40)}\0\0fix: b\n\0\n${'c'.repeat(40)}\0ISO-8859-1\0x\n\nCo-Authored-By: Claude <noreply@anthropic.com>\n`;
  assert.deepEqual(creditedCommits(log), ['a'.repeat(40)]);
});

function sh(cwd, args, env = {}) {
  const r = spawnSync('git', ['-c', 'commit.gpgsign=false', ...args], { cwd, encoding: 'utf8', env: { ...process.env, ...env } });
  assert.equal(r.status, 0, `git ${args.join(' ')}: ${r.stderr}`);
  return r.stdout.trim();
}
const at = (n) => ({ GIT_AUTHOR_DATE: `2026-11-0${n}T10:00:00Z`, GIT_COMMITTER_DATE: `2026-11-0${n}T11:00:00Z` });
async function commit(repo, file, message, n, env = {}) {
  await fs.writeFile(path.join(repo, file), `${file} ${n}\n`);
  sh(repo, ['add', '-A']);
  sh(repo, ['commit', '-q', '--cleanup=verbatim', '-m', message], { ...at(n), ...env });
  return sh(repo, ['rev-parse', 'HEAD']);
}
const info = (repo, sha) => sh(repo, ['log', '-1', '--format=%T|%P|%an <%ae> %aI|%cn <%ce> %cI', sha]);

// main: init; integration: X; unit branch u: plain P, credited C, a merge of the integration head M, credited D
async function project(t) {
  const repo = await fs.realpath(await fs.mkdtemp(path.join(os.tmpdir(), 'orq-strip-')));
  t.after(() => fs.rm(repo, { recursive: true, force: true }));
  sh(repo, ['init', '-q', '-b', 'main']);
  sh(repo, ['config', 'user.name', 'Test User']);
  sh(repo, ['config', 'user.email', 'test@example.invalid']);
  const base = await commit(repo, 'base.txt', 'init', 1);
  sh(repo, ['checkout', '-q', '-b', 'u']);
  const P = await commit(repo, 'p.txt', 'feat: p\n\nCo-authored-by: Ana Lima <ana@example.com>\n', 2, { GIT_AUTHOR_NAME: 'Worker', GIT_AUTHOR_EMAIL: 'w@example.invalid' });
  const C = await commit(repo, 'c.txt', 'feat: c\n\nWhy it is so.\n\nCo-Authored-By: Claude Sonnet 5.5 <noreply@anthropic.com>\n', 3);
  sh(repo, ['checkout', '-q', '-b', 'integration', base]);
  const X = await commit(repo, 'x.txt', 'feat: x from another unit', 4);
  sh(repo, ['checkout', '-q', 'u']);
  sh(repo, ['merge', '-q', '--no-ff', '--no-edit', 'integration'], at(5));
  const M = sh(repo, ['rev-parse', 'HEAD']);
  const D = await commit(repo, 'd.txt', 'fix: d\n\nCo-authored-by: Cursor <cursoragent@cursor.com>\n', 6);
  sh(repo, ['checkout', '-q', 'main']);
  return {
    repo, base, P, C, X, M, D, git: createGit({ exec: defaultExec }),
  };
}

test('stripUnitCredit: rewrites only the unit\'s own credited commits and their descendants; trees, parents, people and dates kept', async (t) => {
  const p = await project(t);
  const r = stripUnitCredit({
    git: p.git, cwd: p.repo, head: p.D, stop: [p.X], branch: 'u', scratch: path.join(p.repo, '.git', 'orq-commit'),
  });
  assert.notEqual(r.head, p.D);
  assert.deepEqual(r.move, { branch: 'u', from: p.D, to: r.head });
  assert.equal(sh(p.repo, ['rev-parse', 'u']), p.D); // moved only once integrated
  moveBranch(p.git, p.repo, r.move);
  assert.equal(sh(p.repo, ['rev-parse', 'u']), r.head); // nothing pushed
  moveBranch(p.git, p.repo, r.move); // the branch is no longer at `from`: left alone, no error
  const [d2, m2, c2, p2] = sh(p.repo, ['rev-list', '--first-parent', '-4', r.head]).split('\n');
  assert.equal(p2, p.P); // nothing to drop and nothing below it changed: the same commit
  assert.equal(sh(p.repo, ['log', '-1', '--format=%B', c2]), 'feat: c\n\nWhy it is so.');
  assert.equal(sh(p.repo, ['log', '-1', '--format=%B', d2]), 'fix: d');
  assert.equal(sh(p.repo, ['log', '-1', '--format=%B', m2]), sh(p.repo, ['log', '-1', '--format=%B', p.M])); // the merge's own message is kept
  assert.deepEqual(sh(p.repo, ['log', '-1', '--format=%P', m2]).split(' '), [c2, p.X]); // its parents mapped, the integration one kept
  for (const [old, now] of [[p.C, c2], [p.M, m2], [p.D, d2]]) {
    const [tree, , author, committer] = info(p.repo, old).split('|');
    const [tree2, , author2, committer2] = info(p.repo, now).split('|');
    assert.deepEqual([tree2, author2, committer2], [tree, author, committer]);
  }
  assert.deepEqual(r.rewritten, 3);
  // again on the rewritten head: nothing to do
  const again = stripUnitCredit({ git: p.git, cwd: p.repo, head: r.head, stop: [p.X], branch: 'u', scratch: path.join(p.repo, '.git', 'orq-commit') });
  assert.deepEqual(again, { head: r.head, rewritten: 0, move: null });
  // the same input gives the same commits: a re-run after a crash finds the same head
  assert.equal(stripUnitCredit({ git: p.git, cwd: p.repo, head: p.D, stop: [p.X], branch: null, scratch: path.join(p.repo, '.git', 'orq-commit') }).head, r.head);
});

test('stripUnitCredit: commits reachable from a stop are never rewritten; a branch that moved on is left alone', async (t) => {
  const p = await project(t);
  const none = stripUnitCredit({ git: p.git, cwd: p.repo, head: p.D, stop: [p.D], branch: 'u', scratch: path.join(p.repo, '.git', 'orq-commit') });
  assert.deepEqual(none, { head: p.D, rewritten: 0, move: null });
  sh(p.repo, ['branch', '-f', 'u', p.M]); // the branch is not at the head being integrated
  const r = stripUnitCredit({ git: p.git, cwd: p.repo, head: p.D, stop: [p.X], branch: 'u', scratch: path.join(p.repo, '.git', 'orq-commit') });
  assert.notEqual(r.head, p.D);
  assert.equal(r.move, null);
  assert.equal(sh(p.repo, ['rev-parse', 'u']), p.M);
});

// a commit object written by hand: headers as given, message as bytes
function object(repo, headers, message) {
  const r = spawnSync('git', ['hash-object', '-t', 'commit', '-w', '--stdin'], { cwd: repo, input: Buffer.concat([Buffer.from(`${headers.join('\n')}\n\n`, 'latin1'), message]) });
  assert.equal(r.status, 0, String(r.stderr));
  return String(r.stdout).trim();
}
const bytes = (repo, sha) => spawnSync('git', ['cat-file', 'commit', sha], { cwd: repo }).stdout;

test('stripUnitCredit: a signature is dropped from a rewritten commit, a merged tag kept; another encoding is never re-encoded', async (t) => {
  const p = await project(t);
  const tree = sh(p.repo, ['rev-parse', `${p.C}^{tree}`]);
  const who = 'Test User <test@example.invalid> 1793000000 +0000';
  const sig = ['gpgsig -----BEGIN PGP SIGNATURE-----', ' ', ' abc', ' -----END PGP SIGNATURE-----'];
  const tag = ['mergetag object ' + p.X, ' type commit', ' tag v1', ' tagger T <t@x> 1793000000 +0000', ' ', ' v1'];
  const signed = object(p.repo, [`tree ${tree}`, `parent ${p.P}`, `author ${who}`, `committer ${who}`, ...sig], Buffer.from('feat: s\n\nCo-Authored-By: Claude <noreply@anthropic.com>\n'));
  const latin = Buffer.from('fix: caf\xe9\n\nCo-Authored-By: Claude <noreply@anthropic.com>\n', 'latin1');
  const encoded = object(p.repo, [`tree ${tree}`, `parent ${signed}`, `author ${who}`, `committer ${who}`, 'encoding ISO-8859-1'], latin);
  const raw = Buffer.from('fix: na\xefve bytes\n', 'latin1'); // not UTF-8, no header saying so
  const odd = object(p.repo, [`tree ${tree}`, `parent ${encoded}`, `author ${who}`, `committer ${who}`], raw);
  const merged = object(p.repo, [`tree ${tree}`, `parent ${odd}`, `parent ${p.X}`, `author ${who}`, `committer ${who}`, ...tag], Buffer.from('Merge tag v1\n\nCo-authored-by: Cursor <cursoragent@cursor.com>\n'));
  const r = stripUnitCredit({ git: p.git, cwd: p.repo, head: merged, stop: [p.X], branch: null, scratch: path.join(p.repo, '.git', 'orq-commit') });
  const [m2, odd2, enc2, sig2] = sh(p.repo, ['rev-list', '--first-parent', '-4', r.head]).split('\n');
  const text = (sha) => bytes(p.repo, sha).toString('latin1');
  assert.ok(!text(sig2).includes('gpgsig') && text(sig2).endsWith('\n\nfeat: s\n'));
  assert.ok(text(m2).includes(`\n${tag.join('\n')}\n`) && text(m2).endsWith('\n\nMerge tag v1\n'));
  // the commits in another encoding keep their message bytes; only their parent moved
  assert.ok(bytes(p.repo, enc2).subarray(-latin.length).equals(latin));
  assert.ok(bytes(p.repo, odd2).subarray(-raw.length).equals(raw));
  assert.equal(sh(p.repo, ['log', '-1', '--format=%P', enc2]), sig2);
  assert.equal(sh(p.repo, ['log', '-1', '--format=%P', odd2]), enc2);
  // a commit object with no message at all
  const bare = spawnSync('git', ['hash-object', '-t', 'commit', '-w', '--stdin', '--literally'], { cwd: p.repo, input: `tree ${tree}\nparent ${signed}\nauthor ${who}\ncommitter ${who}\n` });
  const none = stripUnitCredit({ git: p.git, cwd: p.repo, head: String(bare.stdout).trim(), stop: [p.X], branch: null, scratch: path.join(p.repo, '.git', 'orq-commit') });
  assert.equal(sh(p.repo, ['log', '-1', '--format=%P', none.head]), sig2);
});
